"""Serialize the independently checked graph as transparent Lean data only."""
import hashlib
import json
from pathlib import Path

p = Path(__file__).parent
certificate = p/'certificate.json'
data = json.loads(certificate.read_text())
assert data['graph_exhausted'] and data['highest_A'] == 7
out = Path('Recaman/ThreeNonsuppliedData.lean')
lines = ['/- Generated by docs/data/c1_depth_20261023/generate_lean_data.py.',
         '   Certificate SHA256: '+hashlib.sha256(certificate.read_bytes()).hexdigest(),
         '   This module verifies the finite graph; actual-word simulation is separate. -/',
         (p/'checker_prefix.txt').read_text(),
         'def rowAt (i : Nat) : Row :=']
packed_rows = []
for row in data['rows']:
    w, a, s, az = row['state']
    code = 1
    for c in w:
        code = 2*code+(c == 'A')
    packed = code*512+az*128+s*8+a
    edges = dict(row['edges'])
    child0 = edges['A0']+1 if 'A0' in edges else 0
    child1 = edges['A1']+1 if 'A1' in edges else 0
    packed_rows.append(f'({packed}, {edges["S"]}, {child0}, {child1})')
def tree(lo, hi, indent):
    if hi-lo == 1:
        return [indent+packed_rows[lo]]
    mid = (lo+hi)//2
    return [indent+f'if i < {mid} then']+tree(lo,mid,indent+'  ')+[indent+'else']+tree(mid,hi,indent+'  ')
lines += tree(0,len(packed_rows),'  ')
lines += ['', f'def rows : Table := ⟨{len(packed_rows)}, rowAt⟩', '']
chunks = [(lo,min(32,len(packed_rows)-lo)) for lo in range(0,len(packed_rows),32)]
for lo,count in chunks:
    lines += ['set_option maxHeartbeats 10000000 in',
              f'theorem rows_checked_{lo} : verifiedRange rows {lo} {count}=true := by decide','']
lines += ['theorem rows_verified : verified rows=true := by',
          '  apply List.all_eq_true.mpr', '  intro i hi',
          f'  have hbound : i < {len(packed_rows)} := List.mem_range.mp hi']
def proof_tree(parts,indent):
    if len(parts)==1:
        lo,count=parts[0]
        return [indent+f'exact verifiedRange_at rows {lo} {count} rows_checked_{lo} i (by omega) (by omega)']
    mid=len(parts)//2
    boundary=parts[mid][0]
    return [indent+f'by_cases h{boundary} : i < {boundary}']+proof_tree(parts[:mid],indent+'· ')+proof_tree(parts[mid:],indent+'· ')
# Bullets form nested Lean blocks; use a separate indentation argument.
def proof_blocks(parts,depth):
    indent='  '*depth
    if len(parts)==1:
        lo,count=parts[0]
        return [indent+f'exact verifiedRange_at rows {lo} {count} rows_checked_{lo} i (by omega) (by omega)']
    mid=len(parts)//2; boundary=parts[mid][0]
    left=proof_blocks(parts[:mid],depth+1);right=proof_blocks(parts[mid:],depth+1)
    left[0]=indent+'· '+left[0].lstrip();right[0]=indent+'· '+right[0].lstrip()
    return [indent+f'by_cases h{boundary} : i < {boundary}']+left+right
lines += proof_blocks(chunks,1)
lines += ['', 'theorem initial_member : Member rows ⟨[],0,0,0⟩ := by',
          '  exact ⟨0, by decide, by decide⟩','', 'end Recaman.ThreeNonsuppliedData','']
out.write_text('\n'.join(lines))
print(json.dumps(dict(path=str(out), rows=len(data['rows']),
                     source_sha256=hashlib.sha256(out.read_bytes()).hexdigest())))
